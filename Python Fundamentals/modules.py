# Modules in Python are files that contain Python code. They can define functions, classes, and variables that you can reuse in other Python programs. You can create your own modules or use built-in modules provided by Python.

# How to create a module:
# 1. Create a new Python file with a .py extension. For example, you can create a file named my_module.py.
# 2. Define functions, classes, or variables in that file. For example: 

import module_set

result = module_set.power(2, 3)
